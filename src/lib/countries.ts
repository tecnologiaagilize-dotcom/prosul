/** ISO-2 -> id usado no mapa world-atlas (numérico com 3 dígitos). */
export const atlasId = (iso2: string) => {
  const n = participantCountries.find(([c]) => c === iso2)?.[1];
  return n === undefined ? null : String(n).padStart(3, "0");
};
